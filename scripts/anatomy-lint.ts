// The anatomy lint (docs/WORLDGEN3D.md Q15c, CL-Q2, CL-Q6; ROADMAP F86): compares the anatomy table
// (src/rules/anatomy.ts) with each sprite's measured outline (scripts/lib/silhouette.ts, the same measurement the camera
// framing uses) and writes docs/anatomy-lint.md. Report-only: no threshold, no gate, until the owner sets an expected
// ratio. The sim never reads the art; this script is the only place the two meet.
//   npx tsx scripts/anatomy-lint.ts [--out docs/anatomy-lint.md]
import { writeFileSync } from 'node:fs';
import { framedSpecies, spriteOutline } from './lib/silhouette';
import { SPECIES, SPECIES_BY_ID } from '../src/rules/species';
import { PROTOTYPE } from '../src/rules/heroes';
import { bodyOf } from '../src/rules/sizing';
import { ANATOMY_OVERRIDES, anatomyOf } from '../src/rules/anatomy';
import { defaultRules } from '../src/rules/defaults';

const out = process.argv.includes('--out') ? process.argv[process.argv.indexOf('--out') + 1] : 'docs/anatomy-lint.md';
const RUNGS = [1.45, 2.0, 3.7];
const f2 = (v: number) => v.toFixed(2);
const q = (a: number[], p: number) => { const b = [...a].sort((x, y) => x - y); return b[Math.round(p * (b.length - 1))]; };
const hero = (id: string) => (PROTOTYPE.includes(id) ? `**${id}**` : id);

interface Row { id: string; cls: string; shape: string; h: number; top: number; drop: number; topRatio: number; widthRatio: number; eye: number; eyeFwd: number; inside: boolean; drawnFrac: number }
const rows: Row[] = [];
for (const id of framedSpecies()) {
  const sp = SPECIES_BY_ID[id];
  if (!sp || bodyOf(sp).authored) continue;
  const o = spriteOutline(id)!.outline, a = anatomyOf(sp), drop = o.drop ?? 0;
  const inside = a.eye.up <= o.top && a.eye.fwd <= Math.min(o.right, o.left);
  rows.push({
    id, cls: bodyOf(sp).className, shape: sp.canon?.shape ?? '-', h: a.height, top: o.top, drop, topRatio: o.top / a.height,
    widthRatio: (o.left + o.right) / a.width, eye: a.eye.up, eyeFwd: a.eye.fwd, inside, drawnFrac: (a.eye.up + drop) / (o.top + drop),
  });
}
rows.sort((x, y) => x.id.localeCompare(y.id));
const tops = rows.map((r) => r.topRatio), widths = rows.map((r) => r.widthRatio), fr = rows.map((r) => r.drawnFrac);
const byTop = [...rows].sort((x, y) => y.topRatio - x.topRatio);

// who sees over cover, over every non-authored game species (with or without art)
const classes = defaultRules.size.classes.map((c) => c.name);
const over: Record<string, { n: number; r: number[] }> = Object.fromEntries(classes.map((c) => [c, { n: 0, r: RUNGS.map(() => 0) }]));
const nearRung: string[] = [];
for (const sp of SPECIES) {
  const b = bodyOf(sp);
  if (b.authored) continue;
  const e = anatomyOf(sp).eye.up, c = over[b.className];
  c.n++;
  RUNGS.forEach((r, i) => { if (e > r) c.r[i]++; });
  if (b.sizeClass === 'large' || b.sizeClass === 'xl') for (const r of RUNGS) if (Math.abs(e - r) <= 0.1) nearRung.push(`${hero(sp.id)} (${b.className}, ${sp.canon?.shape ?? '-'}) ${f2(e)} m by ${r} m`);
}

const L: string[] = [];
L.push('# Anatomy lint report', '');
L.push('Generated by `npx tsx scripts/anatomy-lint.ts`; do not hand-edit. Report-only (ROADMAP F86): no threshold and no gate until the owner sets an expected ratio. The sim never reads the art (docs/WORLDGEN3D.md Q15c, CL-Q2, CL-Q6).', '');
L.push('## What it compares', '');
L.push('- **The table:** `anatomyOf(species)` from `src/rules/anatomy.ts` on the default rules: `height` (the sim height, `bodyOf`), `width` (the footprint diameter) and the `eye` (`up` above the feet, `fwd` ahead of the axis), from the defaults by official shape (`rules.anatomy`) and the overrides in `ANATOMY_OVERRIDES`.');
L.push('- **The sprite:** the measured outline of `scripts/lib/silhouette.ts` (the camera framing\'s measurement: idle and walk frames, all eight rows, at the drawn scale, in metres before the billboard stretch): `top` above the anchor (the middle of the ground footprint), `drop` below it, and the side reaches `left` and `right`.');
L.push('- **Drawn top ÷ sim height:** `top / height`.');
L.push('- **Drawn width ÷ table width:** `(left + right) / width`. The outline\'s side reach mixes the body\'s length and width across the eight facings, so this is a rough figure.');
L.push('- **Eye inside the sprite:** `eye.up <= top` and `eye.fwd <= min(left, right)`.');
L.push('- **Eye on the drawn picture:** `(eye.up + drop) / (top + drop)`, from the lowest drawn point (0) to the top (1). Under 0.6 reads as the eye visibly below the drawn head.');
L.push('- **Who sees over cover:** an eye above each cover rung (1.45, 2.00, 3.70 m) over every non-authored game species, art or not.', '');
L.push('## Summary', '');
L.push(`- Species with art: ${rows.length}. Overrides: ${Object.keys(ANATOMY_OVERRIDES).length} (CL adds none: no default eye lies outside its sprite).`);
L.push(`- Drawn top ÷ sim height: min ${f2(q(tops, 0))}, p10 ${f2(q(tops, 0.1))}, median ${f2(q(tops, 0.5))}, p90 ${f2(q(tops, 0.9))}, max ${f2(q(tops, 1))}. Highest: ${byTop.slice(0, 6).map((r) => `${hero(r.id)} ${f2(r.topRatio)}`).join(', ')}. Lowest: ${byTop.slice(-4).reverse().map((r) => `${hero(r.id)} ${f2(r.topRatio)}`).join(', ')}.`);
L.push(`- Drawn width ÷ table width: min ${f2(q(widths, 0))}, median ${f2(q(widths, 0.5))}, max ${f2(q(widths, 1))}.`);
L.push(`- Eye inside the sprite: ${rows.filter((r) => r.inside).length} of ${rows.length}. Smallest margin under the drawn top: ${(() => { const m = [...rows].sort((x, y) => (x.top - x.eye) - (y.top - y.eye))[0]; return `${hero(m.id)} ${f2(m.top - m.eye)} m`; })()}.`);
const low = rows.filter((r) => r.drawnFrac < 0.6).sort((x, y) => x.drawnFrac - y.drawnFrac);
L.push(`- Eye on the drawn picture: min ${f2(q(fr, 0))}, median ${f2(q(fr, 0.5))}, max ${f2(q(fr, 1))}; **${low.length} of ${rows.length} under 0.6**: ${low.map((r) => `${hero(r.id)} (${r.shape}) ${f2(r.drawnFrac)}`).join(', ')}.`, '');
L.push('## Who sees over cover', '');
L.push('| Class | Species | Eye over 1.45 m | over 2.00 m | over 3.70 m |', '|---|---|---|---|---|');
for (const c of classes) L.push(`| ${c} | ${over[c].n} | ${over[c].r.join(' | ')} |`);
L.push('', `Large and Extra Large eyes within 0.10 m of a rung (a wrong shape label flips the result), ${nearRung.length}: ${nearRung.join('; ')}.`, '');
L.push('## Overrides', '', Object.keys(ANATOMY_OVERRIDES).length ? Object.entries(ANATOMY_OVERRIDES).map(([k, v]) => `- ${k}: ${JSON.stringify(v)}`).join('\n') : 'None.', '');
L.push('## Per species', '', 'Heroes in bold. Metres.', '');
L.push('| Species | Class | Shape | Sim height | Drawn top | Top ratio | Width ratio | Eye up | Eye fwd | Eye inside | Eye on picture |', '|---|---|---|---|---|---|---|---|---|---|---|');
for (const r of rows) L.push(`| ${hero(r.id)} | ${r.cls} | ${r.shape} | ${f2(r.h)} | ${f2(r.top)} | ${f2(r.topRatio)} | ${f2(r.widthRatio)} | ${f2(r.eye)} | ${f2(r.eyeFwd)} | ${r.inside ? 'yes' : '**no**'} | ${f2(r.drawnFrac)} |`);
writeFileSync(out, L.join('\n') + '\n');
console.log(`wrote ${out}: ${rows.length} species, top ratio ${f2(q(tops, 0))}–${f2(q(tops, 1))} (median ${f2(q(tops, 0.5))}), ${rows.filter((r) => !r.inside).length} eyes outside, ${low.length} under 0.6 on the picture`);
