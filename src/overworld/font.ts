export const FONT_H = 8;

export function textWidth(s: string): number {
  let w = 0;
  for (const ch of s) w += (G[ch] ?? G['?'])[0].length + 1;
  return Math.max(0, w - 1);
}

/** Draw text into a 2D context at integer pixels; optional 1px drop shadow (DS style). */
export function drawText(ctx: CanvasRenderingContext2D, s: string, x: number, y: number, color: string, shadow?: string, maxChars = Infinity) {
  let cx = Math.round(x);
  let n = 0;
  for (const ch of s) {
    if (n++ >= maxChars) break;
    const g = G[ch] ?? G['?'];
    for (let r = 0; r < g.length; r++)
      for (let c = 0; c < g[r].length; c++) {
        if (g[r][c] !== '#') continue;
        if (shadow) { ctx.fillStyle = shadow; ctx.fillRect(cx + c + 1, y + r, 1, 1); ctx.fillRect(cx + c, y + r + 1, 1, 1); ctx.fillRect(cx + c + 1, y + r + 1, 1, 1); }
      }
    for (let r = 0; r < g.length; r++)
      for (let c = 0; c < g[r].length; c++) {
        if (g[r][c] !== '#') continue;
        ctx.fillStyle = color;
        ctx.fillRect(cx + c, y + r, 1, 1);
      }
    cx += g[0].length + 1;
  }
}

/** word-wrap to a pixel width */
export function wrap(s: string, width: number): string[] {
  const out: string[] = [];
  for (const para of s.split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      const t = line ? line + ' ' + word : word;
      if (textWidth(t) > width && line) { out.push(line); line = word; } else line = t;
    }
    out.push(line);
  }
  return out;
}
