// Original Poke-Watch creature designs. Coordinates: +z forward (face), +y up, x right.
// Roughly 1 unit tall for small creatures; the baker normalises scale per sheet.
// Each design is plain data — tweak a colour or a part and the sprite sheet re-bakes at load.

import type { Design, Part } from './kit';

type V3 = [number, number, number];
const sph = (p: V3, k: V3, c: string, o: Partial<Part> = {}): Part => ({ s: 'sphere', p, k, c, ...o });
const cone = (p: V3, k: V3, c: string, o: Partial<Part> = {}): Part => ({ s: 'cone', p, k, c, ...o });
const cyl = (p: V3, k: V3, c: string, o: Partial<Part> = {}): Part => ({ s: 'cyl', p, k, c, ...o });
const tcone = (p: V3, k: V3, c: string, top: number, o: Partial<Part> = {}): Part => ({ s: 'tcone', p, k, c, top, ...o });
const box = (p: V3, k: V3, c: string, o: Partial<Part> = {}): Part => ({ s: 'box', p, k, c, ...o });
const torus = (p: V3, k: V3, c: string, arc: number, tube: number, o: Partial<Part> = {}): Part => ({ s: 'torus', p, k, c, arc, tube, ...o });

/** Cute eyes: dark oval + two white highlights (same side on both eyes). */
function eyes(x: number, y: number, z: number, s: number, iris = '#1c1a2b', o: { glow?: boolean; tilt?: number; ring?: string } = {}): Part[] {
  const out: Part[] = [];
  if (o.ring) out.push(sph([x, y, z - s * 0.15], [s * 1.25, s * 1.35, s * 0.6], o.ring, { m: true }));
  out.push(sph([x, y, z], [s * 0.78, s, s * 0.55], iris, { m: true, r: [0, 0, o.tilt ?? 0], e: o.glow ? 1 : 0 }));
  if (!o.glow) {
    out.push(sph([x - s * 0.22, y + s * 0.35, z + s * 0.42], [s * 0.3, s * 0.3, s * 0.15], '#ffffff', { e: 1 }));
    out.push(sph([-x - s * 0.22, y + s * 0.35, z + s * 0.42], [s * 0.3, s * 0.3, s * 0.15], '#ffffff', { e: 1 }));
  }
  return out;
}

function legs4(xs: number, zf: number, zb: number, h: number, w: number, c: string, foot?: string): Part[] {
  const out: Part[] = [
    cyl([xs, 0, zf], [w, h, w], c, { m: true, a: 'legF', pv: [xs, h, zf] }),
    cyl([xs, 0, zb], [w, h, w], c, { m: true, a: 'legB', pv: [xs, h, zb] }),
  ];
  if (foot) {
    out.push(sph([xs, 0.02, zf + 0.02], [w * 1.25, w * 0.6, w * 1.4], foot, { m: true, a: 'legF', pv: [xs, h, zf] }));
    out.push(sph([xs, 0.02, zb + 0.02], [w * 1.25, w * 0.6, w * 1.4], foot, { m: true, a: 'legB', pv: [xs, h, zb] }));
  }
  return out;
}

function legs2(xs: number, z: number, h: number, w: number, c: string, foot?: string): Part[] {
  const out: Part[] = [cyl([xs, 0, z], [w, h, w], c, { m: true, a: 'legF', pv: [xs, h, z] })];
  if (foot) out.push(sph([xs, 0.03, z + w * 0.6], [w * 1.4, w * 0.7, w * 1.8], foot, { m: true, a: 'legF', pv: [xs, h, z] }));
  return out;
}

function ring(n: number, f: (i: number, a: number) => Part[]): Part[] {
  const out: Part[] = [];
  for (let i = 0; i < n; i++) out.push(...f(i, (i / n) * Math.PI * 2));
  return out;
}

